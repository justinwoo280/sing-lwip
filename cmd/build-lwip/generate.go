package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

var upstreamSources = []string{
	"core/def.c", "core/inet_chksum.c", "core/init.c", "core/ip.c",
	"core/mem.c", "core/memp.c", "core/netif.c", "core/pbuf.c",
	"core/stats.c", "core/sys.c", "core/tcp.c", "core/tcp_in.c",
	"core/tcp_out.c", "core/timeouts.c", "core/udp.c",
	"core/ipv4/icmp.c", "core/ipv4/ip4.c", "core/ipv4/ip4_addr.c", "core/ipv4/ip4_frag.c",
	"core/ipv6/icmp6.c", "core/ipv6/inet6.c", "core/ipv6/ip6.c",
	"core/ipv6/ip6_addr.c", "core/ipv6/ip6_frag.c", "core/ipv6/nd6.c", "core/ipv6/mld6.c",
	"ports/lib/mem.c", "api/err.c",
}

func generateCommand(root string, args []string) error {
	flags := flag.NewFlagSet("generate", flag.ContinueOnError)
	check := flags.Bool("check", false, "verify generated files without changing them")
	if err := parseFlags(flags, args); err != nil {
		return err
	}
	if _, err := ensureLWIPSource(root); err != nil {
		return err
	}
	if err := generateChecksums(root, *check); err != nil {
		return err
	}
	paths, err := nativeDependencies(root)
	if err != nil {
		return err
	}
	digest := sha256.New()
	for _, path := range paths {
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		digest.Write(data)
	}
	fingerprint := fmt.Sprintf("%x", digest.Sum(nil))
	for _, source := range upstreamSources {
		name := filepath.Join(root, "lwip_"+strings.ReplaceAll(source, "/", "_"))
		hook := ""
		if source == "core/inet_chksum.c" {
			hook = "#include \"checksum.h\"\n#define LWIP_CHKSUM sl_checksum\n"
		}
		text := fmt.Sprintf("//go:build cgo && !with_purego && !with_lwip_prebuilt\n\n// Code generated by go run ./cmd/build-lwip generate; DO NOT EDIT.\n// Source fingerprint: %s\n%s#include \"third_party/lwip/src/%s\"\n", fingerprint, hook, source)
		if source == "core/inet_chksum.c" {
			text += "\nuint16_t sl_checksum_copy(void *destination, const void *source, uint16_t length) {\n    return sl_checksum_copy_impl(destination, source, length);\n}\n"
		}
		if *check {
			data, err := os.ReadFile(name)
			if err != nil || string(data) != text {
				return fmt.Errorf("%s is stale; run go run ./cmd/build-lwip generate", name)
			}
		} else if err := os.WriteFile(name, []byte(text), 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("Verified %d compilation units; source fingerprint %s\n", len(upstreamSources), fingerprint)
	return nil
}
