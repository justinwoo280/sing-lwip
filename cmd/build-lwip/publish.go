package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"time"
)

type nativeBuild struct {
	Dir      string
	ID       string
	Target   target
	Manifest manifest
}

func publishCommand(root string, args []string) error {
	flags := flag.NewFlagSet("publish", flag.ContinueOnError)
	artifacts := flags.String("artifacts", "artifacts", "downloaded native artifact directory")
	branch := flags.String("branch", "go", "output branch: go or go_dev")
	sourceBranch := flags.String("source-branch", "", "verify that the remote source branch still points to this source commit")
	expected := flags.String("expected", "", "comma-separated target IDs (default: complete release catalog)")
	dryRun := flags.Bool("dry-run", false, "prepare and validate commits without pushing")
	if err := parseFlags(flags, args); err != nil {
		return err
	}
	if *branch != "go" && *branch != "go_dev" {
		return fmt.Errorf("publish branch must be go or go_dev")
	}
	head, err := output(root, []string{"git"}, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	status, err := output(root, []string{"git"}, "status", "--porcelain")
	if err != nil {
		return err
	}
	if status != "" {
		return fmt.Errorf("commit source changes before publishing: %s", status)
	}
	source, err := verifyLWIPSource(root)
	if err != nil {
		return err
	}
	fingerprint, err := nativeFingerprint(root)
	if err != nil {
		return err
	}
	ids := releaseIDs()
	if *expected != "" {
		ids = strings.Split(*expected, ",")
	}
	builds, err := loadBuilds(root, *artifacts, head, fingerprint, ids, source)
	if err != nil {
		return err
	}
	if err := checkSourceBranch(root, *sourceBranch, head); err != nil {
		return err
	}
	modData, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return err
	}
	var module string
	for _, line := range strings.Split(string(modData), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 2 && fields[0] == "module" {
			module = fields[1]
			break
		}
	}
	if module == "" {
		return fmt.Errorf("missing module directive")
	}
	directory, err := os.MkdirTemp("", "sing-lwip-publish-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(directory)
	if err := run(root, nil, []string{"git"}, "worktree", "add", "--detach", directory, head); err != nil {
		return err
	}
	defer func() {
		if err := run(root, nil, []string{"git"}, "worktree", "remove", "--force", directory); err != nil {
			fmt.Fprintln(os.Stderr, err)
		}
	}()
	ref := "refs/heads/" + *branch
	previous, err := output(directory, []string{"git"}, "ls-remote", "--heads", "origin", ref)
	if err != nil {
		return err
	}
	if previous != "" {
		if err := run(directory, nil, []string{"git"}, "fetch", "--no-tags", "origin", ref); err != nil {
			return err
		}
		// Keep the source snapshot in the index, appending to published history.
		if err := run(directory, nil, []string{"git"}, "reset", "--soft", "FETCH_HEAD"); err != nil {
			return err
		}
	}
	for _, build := range builds {
		if err := writeLibraryModule(directory, module, build); err != nil {
			return err
		}
	}
	if err := run(directory, nil, []string{"git"}, "add", "-f", "--", "lib"); err != nil {
		return err
	}
	if err := run(directory, nil, []string{"git"}, "commit", "-m", "Build native libraries from "+head[:12]); err != nil {
		return err
	}
	librariesCommit, err := output(directory, []string{"git"}, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	date, err := output(directory, []string{"git"}, "show", "-s", "--format=%cI", librariesCommit)
	if err != nil {
		return err
	}
	stamp, err := time.Parse(time.RFC3339, date)
	if err != nil {
		return err
	}
	version := "v0.0.0-" + stamp.UTC().Format("20060102150405") + "-" + librariesCommit[:12]
	goEnv := map[string]string{"GOWORK": "off"}
	for _, build := range builds {
		path := module + "/lib/" + build.ID
		text := fmt.Sprintf("// Code generated by build-lwip publish; DO NOT EDIT.\n//go:build cgo && !with_purego && with_lwip_prebuilt && (%s)\n\npackage lwip\n\nimport _ %q\n", build.Target.constraint(build.Manifest.Libc), path)
		formatted, err := format.Source([]byte(text))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(directory, "prebuilt_"+build.ID+".go"), formatted, 0o644); err != nil {
			return err
		}
		if err := run(directory, goEnv, []string{"go"}, "mod", "edit", "-require="+path+"@"+version, "-replace="+path+"=./lib/"+build.ID); err != nil {
			return err
		}
	}
	if err := run(directory, goEnv, []string{"go"}, "mod", "tidy"); err != nil {
		return err
	}
	if err := verifyHostLibraries(directory, builds); err != nil {
		return err
	}
	// Validate the exact local module graph before any public ref changes.
	graph, err := outputEnv(directory, goEnv, []string{"go"}, "list", "-m", "all")
	if err != nil {
		return err
	}
	for _, build := range builds {
		path := module + "/lib/" + build.ID
		if !strings.Contains(graph, path+" "+version+" => ") {
			return fmt.Errorf("published module version changed during tidy: %s", path)
		}
		if err := run(directory, goEnv, []string{"go"}, "mod", "edit", "-dropreplace="+path); err != nil {
			return err
		}
	}
	index := struct {
		ABI              int        `json:"abi"`
		SourceCommit     string     `json:"source_commit"`
		LibrariesCommit  string     `json:"libraries_commit"`
		LibrariesVersion string     `json:"libraries_version"`
		LWIPSource       sourceLock `json:"lwip_source"`
		Targets          []string   `json:"targets"`
	}{2, head, librariesCommit, version, source, ids}
	data, err := json.MarshalIndent(index, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(directory, "native-build.json"), append(data, '\n'), 0o644); err != nil {
		return err
	}
	if err := run(directory, nil, []string{"git"}, "add", "-f", "--", "go.mod", "native-build.json", "prebuilt_*.go"); err != nil {
		return err
	}
	if _, err := os.Stat(filepath.Join(directory, "go.sum")); err == nil {
		if err := run(directory, nil, []string{"git"}, "add", "--", "go.sum"); err != nil {
			return err
		}
	}
	if err := run(directory, nil, []string{"git"}, "commit", "-m", "Pin platform libraries for "+head[:12]); err != nil {
		return err
	}
	commit, err := output(directory, []string{"git"}, "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	if !*dryRun {
		if err := checkSourceBranch(root, *sourceBranch, head); err != nil {
			return err
		}
		if err := run(directory, nil, []string{"git"}, "push", "origin", "HEAD:"+ref); err != nil {
			return err
		}
	}
	fmt.Printf("Source: %s\nNative modules: %s\n%s: %s\n", head, version, *branch, commit)
	return nil
}

func checkSourceBranch(root, branch, head string) error {
	if branch == "" {
		return nil
	}
	if err := run(root, nil, []string{"git"}, "check-ref-format", "refs/heads/"+branch); err != nil {
		return err
	}
	remote, err := output(root, []string{"git"}, "ls-remote", "--heads", "origin", "refs/heads/"+branch)
	if err != nil {
		return err
	}
	fields := strings.Fields(remote)
	if len(fields) != 2 || fields[0] != head {
		return fmt.Errorf("source branch %s moved; build its current commit before publishing", branch)
	}
	return nil
}

func loadBuilds(root, artifacts, revision, fingerprint string, expected []string, source sourceLock) ([]nativeBuild, error) {
	wanted := make(map[string]bool)
	for _, id := range expected {
		if wanted[id] || id == "" {
			return nil, fmt.Errorf("duplicate/empty expected target %q", id)
		}
		wanted[id] = true
	}
	builds := make(map[string]nativeBuild)
	err := filepath.WalkDir(artifacts, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || entry.Name() != "manifest.json" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var meta manifest
		if err := json.Unmarshal(data, &meta); err != nil {
			return err
		}
		if meta.ABI != 2 || meta.SourceRevision != revision || meta.NativeSourceSHA256 != fingerprint || meta.LWIPSource != source {
			return fmt.Errorf("%s: stale binding/lwIP revision or fingerprint, or incompatible ABI", path)
		}
		t, err := parseTarget(meta.Target)
		if err != nil {
			return err
		}
		if t.GOOS == "linux" && meta.Libc != "gnu" && meta.Libc != "musl" {
			return fmt.Errorf("%s: invalid libc", path)
		}
		id := t.libraryID(meta.Libc)
		if _, found := builds[id]; found {
			return fmt.Errorf("duplicate artifact target %s", id)
		}
		directory := filepath.Dir(path)
		allowed := map[string]bool{"libsing-lwip.a": true, "bridge.h": true, "LICENSE": true, "LWIP-LICENSE": true, t.library(): true}
		for _, name := range []string{"libsing-lwip.a", "bridge.h", "LICENSE", "LWIP-LICENSE"} {
			if meta.Files[name] == "" {
				return fmt.Errorf("%s: missing %s", path, name)
			}
		}
		for name, digest := range meta.Files {
			if !allowed[name] {
				return fmt.Errorf("%s: unexpected library payload %q", path, name)
			}
			file := filepath.Join(directory, name)
			info, err := os.Lstat(file)
			if err != nil || !info.Mode().IsRegular() {
				return fmt.Errorf("%s: missing/non-regular payload", file)
			}
			hash, err := fileHash(file)
			if err != nil || hash != digest {
				return fmt.Errorf("%s: checksum mismatch", file)
			}
			if name == t.library() {
				if err := checkArch(file, t.Arch); err != nil {
					return err
				}
			}
		}
		archive, err := os.ReadFile(filepath.Join(directory, "libsing-lwip.a"))
		if err != nil || !strings.HasPrefix(string(archive), "!<arch>\n") {
			return fmt.Errorf("%s: expected a self-contained static archive", path)
		}
		headerHash, err := fileHash(filepath.Join(root, "bridge.h"))
		if err != nil || meta.Files["bridge.h"] != headerHash {
			return fmt.Errorf("%s: C ABI header mismatch", path)
		}
		if meta.Purego && meta.Files[t.library()] == "" {
			return fmt.Errorf("%s: missing purego dynamic library", path)
		}
		builds[id] = nativeBuild{directory, id, t, meta}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(builds) != len(expected) {
		return nil, fmt.Errorf("expected %d targets, received %d", len(expected), len(builds))
	}
	result := make([]nativeBuild, 0, len(expected))
	for _, id := range expected {
		build, ok := builds[id]
		if !ok {
			return nil, fmt.Errorf("missing target %s", id)
		}
		result = append(result, build)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].ID < result[j].ID })
	return result, nil
}

func writeLibraryModule(directory, module string, build nativeBuild) error {
	out := filepath.Join(directory, "lib", build.ID)
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	for name := range build.Manifest.Files {
		if err := copyFile(filepath.Join(build.Dir, name), filepath.Join(out, name)); err != nil {
			return err
		}
	}
	// Public metadata contains source/toolchain identities, not build-machine paths.
	meta := build.Manifest
	meta.CC, meta.CFlags, meta.LDFlags = "", nil, nil
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	files := map[string]string{
		"manifest.json": string(data) + "\n",
		"go.mod":        "module " + module + "/lib/" + build.ID + "\n\ngo 1.24.0\n",
		"library.go":    fmt.Sprintf("// Code generated by build-lwip publish; DO NOT EDIT.\npackage library\n\nconst ABI = 2\nconst SourceCommit = %q\n", meta.SourceRevision),
		"link_cgo.go":   fmt.Sprintf("// Code generated by build-lwip publish; DO NOT EDIT.\n//go:build cgo && !with_purego && with_lwip_prebuilt && (%s)\n\npackage library\n\n// #cgo LDFLAGS: ${SRCDIR}/libsing-lwip.a\nimport \"C\"\n", build.Target.constraint(meta.Libc)),
	}
	for name, text := range files {
		data := []byte(text)
		if strings.HasSuffix(name, ".go") {
			data, err = format.Source(data)
			if err != nil {
				return err
			}
		}
		if err := os.WriteFile(filepath.Join(out, name), data, 0o644); err != nil {
			return err
		}
	}
	var names []string
	for name := range build.Manifest.Files {
		names = append(names, name)
	}
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	var sums strings.Builder
	for _, name := range names {
		hash, err := fileHash(filepath.Join(out, name))
		if err != nil {
			return err
		}
		fmt.Fprintf(&sums, "%s  %s\n", hash, name)
	}
	return os.WriteFile(filepath.Join(out, "SHA256SUMS"), []byte(sums.String()), 0o644)
}

func verifyHostLibraries(directory string, builds []nativeBuild) error {
	for _, build := range builds {
		t := build.Target
		if t.GOOS != runtime.GOOS || t.Arch != runtime.GOARCH || t.Simulator || build.Manifest.Libc == "musl" {
			continue
		}
		env := map[string]string{"GOWORK": "off", "GOOS": runtime.GOOS, "GOARCH": runtime.GOARCH, "CGO_ENABLED": "1", "CC": envDefault("HOST_CC", "cc")}
		if err := run(directory, env, []string{"go"}, "test", "-count=1", "-tags", "with_lwip_prebuilt", "."); err != nil {
			return fmt.Errorf("prebuilt CGO consumer: %w", err)
		}
		if build.Manifest.Purego {
			env["CGO_ENABLED"] = "0"
			env["SING_LWIP_LIBRARY"] = filepath.Join(directory, "lib", build.ID, t.library())
			command := []string{"test", "-count=1", "-tags", "with_purego"}
			if t.GOOS == "freebsd" {
				command = append(command, "-gcflags=github.com/ebitengine/purego/internal/fakecgo=-std")
			}
			if t.puregoInterpreter() != "" {
				command = append(command, "-ldflags=-I="+t.puregoInterpreter())
			}
			if err := run(directory, env, []string{"go"}, append(command, ".")...); err != nil {
				return fmt.Errorf("published PureGo consumer: %w", err)
			}
		}
	}
	return nil
}
