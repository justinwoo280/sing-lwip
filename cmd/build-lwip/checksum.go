package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Emit GNU/Clang extended assembly, letting the C compiler manage register
// allocation and ABI details (ELF, Mach-O, MinGW and clang-cl). Only baseline
// target features are used: NEON on arm64, SSE2 when enabled by the x86 compiler,
// ARM32 NEON and s390x VX only when enabled by the target toolchain. Linux Power
// also carries a POWER9-targeted function behind a cached runtime HWCAP check.
// The same generated header is consumed by source-CGO and native library builds.
func checksumHeader() string {
	var out strings.Builder
	out.WriteString(`/* Code generated by go run ./cmd/build-lwip generate; DO NOT EDIT. */
#ifndef SING_LWIP_CHECKSUM_GENERATED_H
#define SING_LWIP_CHECKSUM_GENERATED_H
/* Each kernel consumes 1..1024 whole 64-byte blocks and returns a uint32 sum
 * of native-endian uint16 words. No lane or final sum can overflow at 64 KiB. */
#if !defined(SING_LWIP_CHECKSUM_GENERIC) && (defined(__GNUC__) || defined(__clang__))
#if defined(__aarch64__) && !defined(__AARCH64EB__)
#define SL_CHECKSUM_BLOCKS "neon-arm64"
`)
	asm := func(format string, args ...any) {
		if len(args) > 0 {
			format = fmt.Sprintf(format, args...)
		}
		fmt.Fprintf(&out, "        %q\n", format+"\n\t")
	}
	functionAttribute := ""
	begin := func(copy bool) {
		name, destination := "sl_checksum_blocks", ""
		if copy {
			out.WriteString("#ifndef SING_LWIP_CHECKSUM_COPY_SEPARATE\n#define SL_CHECKSUM_COPY_BLOCKS 1\n")
			name, destination = "sl_checksum_copy_blocks", "uint8_t **destination, "
		}
		fmt.Fprintf(&out, "static inline %suint32_t %s(%sconst uint8_t **data, unsigned blocks) {\n    const uint8_t *p = *data;\n", functionAttribute, name, destination)
		if copy {
			out.WriteString("    uint8_t *d = *destination;\n")
		}
		out.WriteString("    uint32_t sum;\n    __asm__ (\n")
	}
	pointerConstraint := "r"
	end := func(copy bool, clobbers string) {
		fmt.Fprintf(&out, `        : [p] "+&%s" (p), [blocks] "+&r" (blocks), [sum] "=r" (sum)`, pointerConstraint)
		if copy {
			fmt.Fprintf(&out, `, [d] "+&%s" (d)`, pointerConstraint)
		}
		fmt.Fprintf(&out, "\n        :\n        : %s, \"cc\", \"memory\");\n    *data = p;\n", clobbers)
		if copy {
			out.WriteString("    *destination = d;\n")
		}
		out.WriteString("    return sum;\n}\n")
		if copy {
			out.WriteString("#endif\n")
		}
	}
	for _, copy := range []bool{false, true} {
		begin(copy)
		for i := 0; i < 4; i++ {
			asm("movi v%d.4s, #0", i)
		}
		asm("1:")
		asm("ldp q4, q5, [%[p]], #32")
		asm("ldp q6, q7, [%[p]], #32")
		if copy {
			asm("stp q4, q5, [%[d]], #32")
			asm("stp q6, q7, [%[d]], #32")
		}
		for i := 0; i < 4; i++ {
			asm("uadalp v%d.4s, v%d.8h", i, i+4)
		}
		asm("subs %w[blocks], %w[blocks], #1")
		asm("b.ne 1b")
		asm("add v0.4s, v0.4s, v1.4s")
		asm("add v2.4s, v2.4s, v3.4s")
		asm("add v0.4s, v0.4s, v2.4s")
		asm("addv s0, v0.4s")
		asm("fmov %w[sum], s0")
		end(copy, `"v0", "v1", "v2", "v3", "v4", "v5", "v6", "v7"`)
	}
	out.WriteString(`#elif (defined(__x86_64__) || defined(__i386__)) && defined(__SSE2__)
#define SL_CHECKSUM_BLOCKS "sse2"
`)
	for _, copy := range []bool{false, true} {
		begin(copy)
		for i := 0; i < 4; i++ {
			asm("pxor %%%%xmm%d, %%%%xmm%d", i, i)
		}
		asm("pxor %%xmm7, %%xmm7")
		asm("1:")
		for i := 0; i < 4; i++ {
			asm("movdqu %d(%%[p]), %%%%xmm4", i*16)
			if copy {
				asm("movdqu %%%%xmm4, %d(%%[d])", i*16)
			}
			asm("movdqa %%xmm4, %%xmm5")
			asm("punpcklwd %%xmm7, %%xmm4")
			asm("punpckhwd %%xmm7, %%xmm5")
			asm("paddd %%%%xmm4, %%%%xmm%d", i)
			asm("paddd %%%%xmm5, %%%%xmm%d", i)
		}
		asm("add $64, %[p]")
		if copy {
			asm("add $64, %[d]")
		}
		asm("sub $1, %k[blocks]")
		asm("jnz 1b")
		asm("paddd %%xmm1, %%xmm0")
		asm("paddd %%xmm3, %%xmm2")
		asm("paddd %%xmm2, %%xmm0")
		asm("pshufd $0x4e, %%xmm0, %%xmm4")
		asm("paddd %%xmm4, %%xmm0")
		asm("pshufd $0xb1, %%xmm0, %%xmm4")
		asm("paddd %%xmm4, %%xmm0")
		asm("movd %%xmm0, %k[sum]")
		end(copy, `"xmm0", "xmm1", "xmm2", "xmm3", "xmm4", "xmm5", "xmm7"`)
	}
	out.WriteString(`#elif defined(__arm__) && defined(__ARM_NEON) && !defined(__ARMEB__)
#define SL_CHECKSUM_BLOCKS "neon-arm"
`)
	for _, copy := range []bool{false, true} {
		begin(copy)
		for i := 0; i < 4; i++ {
			asm("veor q%d, q%d, q%d", i, i, i)
		}
		asm("1:")
		asm("vld1.8 {d16-d19}, [%[p]]!")
		asm("vld1.8 {d20-d23}, [%[p]]!")
		if copy {
			asm("vst1.8 {d16-d19}, [%[d]]!")
			asm("vst1.8 {d20-d23}, [%[d]]!")
		}
		for i := 0; i < 4; i++ {
			asm("vpadal.u16 q%d, q%d", i, i+8)
		}
		asm("subs %[blocks], %[blocks], #1")
		asm("bne 1b")
		asm("vadd.i32 q0, q0, q1")
		asm("vadd.i32 q2, q2, q3")
		asm("vadd.i32 q0, q0, q2")
		asm("vpadd.i32 d0, d0, d1")
		asm("vpadd.i32 d0, d0, d0")
		asm("vmov %[sum], s0")
		end(copy, `"q0", "q1", "q2", "q3", "q8", "q9", "q10", "q11"`)
	}
	out.WriteString(`#elif defined(__powerpc64__) && defined(__linux__)
#define SL_CHECKSUM_BLOCKS "vsx-power9"
#if defined(_ARCH_PWR9)
#define SL_POWER9_TARGET
#else
#include <sys/auxv.h>
#if defined(__clang__)
#define SL_POWER9_TARGET __attribute__((target("power9-vector")))
#else
#define SL_POWER9_TARGET __attribute__((target("cpu=power9")))
#endif
/* Keep generic builds runnable on POWER8 and earlier. Cache only the CPU
 * capability, with relaxed atomics so independent stacks may initialize it
 * concurrently. A missing HWCAP2 entry conservatively selects portable C. */
static inline int sl_checksum_power9_available(void) {
    static unsigned cached;
    unsigned value = __atomic_load_n(&cached, __ATOMIC_RELAXED);
    if (!value) {
        /* Linux PPC_FEATURE_HAS_ALTIVEC | PPC_FEATURE_HAS_VSX, and
         * PPC_FEATURE2_ARCH_3_00 (also present on POWER10). */
        value = ((getauxval(AT_HWCAP) & 0x10000080UL) == 0x10000080UL &&
                 (getauxval(AT_HWCAP2) & 0x00800000UL)) ? 2 : 1;
        __atomic_store_n(&cached, value, __ATOMIC_RELAXED);
    }
    return value == 2;
}
#define SL_CHECKSUM_AVAILABLE() sl_checksum_power9_available()
#endif
/* LXV/STXV preserve native halfwords at arbitrary byte alignments. VMSUMUHM
 * widens pairs of unsigned halfwords into four word accumulators. Four
 * independent chains cover each 64-byte block; their complete 64-KiB sum
 * remains below INT32_MAX, including all-ones input, so VSUMSWS cannot saturate.
 * Lane order is immaterial to the sum, and stores invert the exact loads. */
`)
	pointerConstraint = "b" // Power load/store base register r0 means literal zero.
	functionAttribute = "SL_POWER9_TARGET "
	for _, copy := range []bool{false, true} {
		begin(copy)
		for i := 0; i < 4; i++ {
			asm("vxor %d, %d, %d", i, i, i)
		}
		asm("vspltish 8, 1")
		asm("vxor 9, 9, 9")
		asm("clrldi %[blocks], %[blocks], 32")
		asm("mtctr %[blocks]")
		asm("1:")
		for i := 0; i < 4; i++ {
			asm("lxv %d, %d(%%[p])", 36+i, i*16)
		}
		if copy {
			for i := 0; i < 4; i++ {
				asm("stxv %d, %d(%%[d])", 36+i, i*16)
			}
			asm("addi %[d], %[d], 64")
		}
		for i := 0; i < 4; i++ {
			asm("vmsumuhm %d, %d, 8, %d", i, i+4, i)
		}
		asm("addi %[p], %[p], 64")
		asm("bdnz 1b")
		asm("vadduwm 0, 0, 1")
		asm("vadduwm 2, 2, 3")
		asm("vadduwm 0, 0, 2")
		asm("vsumsws 0, 0, 9")
		asm("mfvsrld %[sum], 32")
		end(copy, `"v0", "v1", "v2", "v3", "v4", "v5", "v6", "v7", "v8", "v9", "ctr"`)
	}
	functionAttribute = ""
	out.WriteString(`#elif defined(__s390x__) && defined(__VX__)
#define SL_CHECKSUM_BLOCKS "vx-s390x"
/* z13 Vector Facility: VSUMH widens pairs of unsigned halfwords into words.
 * Its third operand contributes only a halfword, so use zero there and VAF
 * for full-width accumulation; reusing an accumulator in VSUMH loses carries.
 * Independent accumulators avoid a loop-carried serial sum. At most 1024
 * blocks contribute 4096 halfwords per lane, so neither a lane nor the
 * final uint32 sum can overflow. Big-endian lanes match lwIP's native order.
 * Only call-clobbered v16..v24 are used; address operands must exclude r0. */
`)
	pointerConstraint = "a"
	for _, copy := range []bool{false, true} {
		begin(copy)
		accumulators := 4
		if copy {
			accumulators = 2
		}
		for i := 0; i < accumulators; i++ {
			asm("vzero %%%%v%d", 16+i)
		}
		asm("vzero %%v24")
		asm("1:")
		if copy {
			asm("vlm %%v20, %%v23, 0(%[p])")
			asm("vstm %%v20, %%v23, 0(%[d])")
			asm("la %[d], 64(%[d])")
		} else {
			for i := 0; i < 4; i++ {
				asm("vl %%%%v%d, %d(%%[p])", 20+i, 16*i)
			}
		}
		for i := 0; i < 4; i++ {
			asm("vsumh %%%%v%d, %%%%v%d, %%%%v24", 20+i, 20+i)
			asm("vaf %%%%v%d, %%%%v%d, %%%%v%d", 16+i%accumulators, 16+i%accumulators, 20+i)
		}
		asm("la %[p], 64(%[p])")
		asm("brct %[blocks], 1b")
		asm("vaf %%v16, %%v16, %%v17")
		if !copy {
			asm("vaf %%v18, %%v18, %%v19")
			asm("vaf %%v16, %%v16, %%v18")
		}
		asm("vsumqf %%v16, %%v16, %%v24")
		asm("vlgvf %[sum], %%v16, 3")
		clobbers := `"v16", "v17", "v20", "v21", "v22", "v23", "v24"`
		if !copy {
			clobbers += `, "v18", "v19"`
		}
		end(copy, clobbers)
	}
	out.WriteString(`#endif
#endif
#endif
`)
	return out.String()
}

func generateChecksums(root string, check bool) error {
	name, text := filepath.Join(root, "checksum_generated.h"), checksumHeader()
	if check {
		data, err := os.ReadFile(name)
		if err != nil || string(data) != text {
			return fmt.Errorf("%s is stale; run go run ./cmd/build-lwip generate", name)
		}
		return nil
	}
	return os.WriteFile(name, []byte(text), 0o644)
}
